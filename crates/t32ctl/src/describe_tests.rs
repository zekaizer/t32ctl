use serde_json::Value;

use super::*;

fn strings(v: &Value) -> Vec<String> {
    v.as_array().unwrap().iter().map(|s| s.as_str().unwrap().to_string()).collect()
}

#[test]
fn the_schema_lists_every_leaf_grade_tag_and_exit() {
    let doc: Value = serde_json::from_str(&json()).unwrap();
    assert_eq!(doc["schema"], "t32ctl.describe/1");
    assert_eq!(doc["version"], env!("CARGO_PKG_VERSION"));
    let paths: Vec<&str> = doc["commands"].as_array().unwrap().iter().map(|c| c["path"].as_str().unwrap()).collect();
    assert_eq!(paths, SPECS.iter().map(|s| s.path.join(" ")).collect::<Vec<_>>());
    let status = &doc["commands"][0];
    assert_eq!(status["usage"], "t32ctl read status [--full]");
    assert_eq!(status["waits"], "-");
    assert_eq!(status["connects"], true);
    assert_eq!(
        strings(&status["examples"]),
        ["t32ctl read status", "t32ctl read status --full", "t32ctl read status --json"]
    );
    assert_eq!(status["args"][0]["flag"], "--full");
    assert_eq!(status["args"][0]["values"], serde_json::json!([]));
    let describe = &doc["commands"][4];
    assert_eq!(doc["commands"][1]["usage"], "t32ctl read mem LOC [--len SIZE] [--width 1|2|4|8] [--to NAME]");
    assert_eq!(doc["commands"][2]["usage"], "t32ctl read reg [NAME...]");
    assert_eq!(doc["commands"][2]["args"][0]["multiple"], true);
    assert_eq!(doc["commands"][3]["usage"], "t32ctl read procs [NAME]");
    assert_eq!(doc["commands"][3]["connects"], false);
    assert_eq!(describe["usage"], "t32ctl read describe [--format json|skill|permissions]");
    assert_eq!(strings(&describe["args"][0]["values"]), ["json", "skill", "permissions"]);
    assert_eq!(describe["connects"], false);
    let grades: Vec<&str> = doc["grades"].as_array().unwrap().iter().map(|g| g["name"].as_str().unwrap()).collect();
    assert_eq!(grades, ["read", "run", "write", "sys", "burn", "raw", "admin"]);
    let tags: Vec<&str> = doc["errors"].as_array().unwrap().iter().map(|e| e["tag"].as_str().unwrap()).collect();
    assert_eq!(tags, ErrorKind::ALL.map(ErrorKind::tag));
    let codes: Vec<u64> = doc["exits"].as_array().unwrap().iter().map(|e| e["code"].as_u64().unwrap()).collect();
    assert_eq!(codes, [0, 1, 2, 3, 4, 5, 130]);
    let flags: Vec<&str> =
        doc["global_flags"].as_array().unwrap().iter().map(|f| f["flag"].as_str().unwrap()).collect();
    assert_eq!(flags, ["--json", "--build"]);
    assert_eq!(doc["global_flags"][1]["value"], "DIR");
    assert!(doc["notation"].as_array().unwrap().iter().any(|f| f["form"] == "register-relative"));
}

#[test]
fn the_snippet_never_allows_a_never_allow_rule_and_denies_the_operator_files() {
    let doc: Value = serde_json::from_str(&permissions()).unwrap();
    let allow = strings(&doc["permissions"]["allow"]);
    let never = strings(&doc["never_allow"]);
    assert_eq!(allow, ["Bash(t32ctl read:*)", "Bash(t32ctl run:*)"]);
    assert_eq!(never, ["Bash(t32ctl burn:*)", "Bash(t32ctl raw:*)"]);
    assert!(never.iter().all(|r| !allow.contains(r)));
    assert_eq!(
        strings(&doc["permissions"]["ask"]),
        ["Bash(t32ctl write:*)", "Bash(t32ctl sys:*)", "Bash(t32ctl burn:*)", "Bash(t32ctl raw:*)"]
    );
    let deny = strings(&doc["permissions"]["deny"]);
    assert_eq!(deny[0], "Bash(t32ctl admin:*)");
    for p in PROTECTED {
        assert!(deny.contains(&format!("Edit({p})")) && deny.contains(&format!("Write({p})")), "{p}");
    }
    assert!(permissions().starts_with("{\n  \"permissions\": {\n    \"allow\": [\n      \"Bash(t32ctl read:*)\","));
}

#[test]
fn the_skill_blocks_are_tables_between_their_markers() {
    let text = skill();
    for name in ["commands", "exits", "errors"] {
        let start =
            format!("<!-- {name}:start (generated by `t32ctl read describe --format skill`; do not edit) -->\n");
        let end = format!("<!-- {name}:end -->\n");
        assert!(text.contains(&start) && text.contains(&end), "{name}");
    }
    assert!(text.starts_with(
        "<!-- commands:start (generated by `t32ctl read describe --format skill`; do not edit) -->\n\
         | Command | Does | Waits for |\n|---|---|---|\n\
         | `t32ctl read status [--full]` | Header, target and CPU check, profile, PowerView; `--full` adds \
         `profile=<hash>`, the binding, the config, and the state directory | - |\n\
         | `t32ctl read mem LOC [--len SIZE] [--width 1\\|2\\|4\\|8] [--to NAME]` | Memory as `0x` cells, or into a \
         file in the output directory | `--to`: the transfer, bounded |\n\
         | `t32ctl read reg [NAME...]` | Registers of PowerView's selected core; no name: the general-purpose set | - \
         |\n\
         | `t32ctl read procs [NAME]` | Board procedures, grade, parameters, `profile=<hash>` | no connection |\n\
         | `t32ctl read describe [--format json\\|skill\\|permissions]` | Static command schema | no connection |\n\
         | `t32ctl read proc NAME [--PARAM VALUE...]` | Run a read-grade board procedure | the script |\n\
         | `t32ctl run proc NAME [--PARAM VALUE...]` | Run a run-grade board procedure | the script |\n\
         | `t32ctl write proc NAME [--PARAM VALUE...]` | Run a write-grade board procedure | the script |\n\
         | `t32ctl sys proc NAME [--PARAM VALUE...]` | Run a sys-grade board procedure | the script |\n\
         | `t32ctl burn proc NAME [--PARAM VALUE...]` | Run a burn-grade board procedure (persistent storage) | the \
         script |\n\
         | `t32ctl raw cmd 'TEXT'` | One PRACTICE command | the command |\n\
         | `t32ctl raw eval 'EXPR'` | One PRACTICE function | the function |\n\
         \nFlags on every command: `--json`, `--build DIR`.\n<!-- commands:end -->\n\n"
    ));
    assert!(text.contains("| 130 | interrupted | The call was interrupted;"));
    assert!(text.contains("| `rcl-locked` | 4 | PowerView's API lock is held by another RCL client (status 123). |\n"));
    assert!(text.ends_with("<!-- errors:end -->\n"));
}
